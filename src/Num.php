<?php
declare(strict_types=1);

namespace App;

final class Num
{
    private const DIGITS = [
        '0' => '۰', '1' => '۱', '2' => '۲', '3' => '۳', '4' => '۴',
        '5' => '۵', '6' => '۶', '7' => '۷', '8' => '۸', '9' => '۹',
    ];

    private const REVERSE = [
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
    ];

    public static function fa(mixed $value): string
    {
        return strtr((string) $value, self::DIGITS);
    }

    /** Convert Persian/Arabic digits to English. */
    public static function en(mixed $value): string
    {
        return strtr((string) $value, self::REVERSE);
    }
}